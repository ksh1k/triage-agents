"""Compile the benign test programs in data/samples/src/ into Windows PE files.

Uses Zig's bundled C compiler (the `ziglang` dev dependency), which can build
Windows executables from any OS, so no Visual Studio or MinGW install is needed.

The outputs in data/samples/bin/ are committed so tests run without a compiler.
They are only ever parsed statically, never executed.

Usage:  uv run python scripts/build_test_bins.py
"""

from __future__ import annotations

import hashlib
import random
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "samples" / "src"
BIN = ROOT / "data" / "samples" / "bin"

HIGH_ENTROPY_BYTES = 16384
SEED = 20261119  # fixed seed, so the generated file is identical on every build


def write_high_entropy_source() -> Path:
    """Generate a C file embedding 16 KB of pseudo-random bytes.

    Random bytes have entropy close to 8 bits/byte, the same signal that packed
    or encrypted payloads give off, so this exercises the entropy detector with
    a file that is harmless.
    """
    rng = random.Random(SEED)
    data = bytes(rng.randrange(256) for _ in range(HIGH_ENTROPY_BYTES))
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n    ".join(rows)
    source = f"""/* GENERATED by scripts/build_test_bins.py - do not edit.
 * Benign test program #3: carries {HIGH_ENTROPY_BYTES} pseudo-random bytes (seed {SEED})
 * so one section has near-maximal entropy, like a packed or encrypted payload.
 * It only prints a checksum. Never executed by this project. */
#include <stdio.h>

static const unsigned char kBlob[{HIGH_ENTROPY_BYTES}] = {{
    {body}
}};

int main(void) {{
    unsigned long sum = 0;
    for (unsigned i = 0; i < sizeof kBlob; i++) sum = (sum * 31u) + kBlob[i];
    printf("checksum: %lu\\n", sum);
    return 0;
}}
"""
    path = SRC / "high_entropy.c"
    path.write_text(source, encoding="utf-8", newline="\n")
    return path


def compile_c(source: Path, output: Path) -> None:
    cmd = [sys.executable, "-m", "ziglang", "cc", "-target", "x86_64-windows-gnu",
           "-O2", "-s", "-o", str(output), str(source)]
    subprocess.run(cmd, check=True)


def main() -> int:
    BIN.mkdir(parents=True, exist_ok=True)
    write_high_entropy_source()
    for source in sorted(SRC.glob("*.c")):
        output = BIN / f"{source.stem}.exe"
        compile_c(source, output)
        digest = hashlib.sha256(output.read_bytes()).hexdigest()
        print(f"{output.relative_to(ROOT)}  {output.stat().st_size:>7} bytes  sha256={digest}")
    for leftover in BIN.glob("*.pdb"):
        leftover.unlink()
    return 0


if __name__ == "__main__":
    sys.exit(main())
